import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const index = read('frontend/index.html');
const iphone = read('frontend/index.iphone.html');
const sw = read('frontend/sw.js');
const css = read('frontend/styles/studio-edition.css');
const nexusCss = read('frontend/styles/nexus-edition.css');
const js = read('frontend/src/studio-edition.js');
const config = read('frontend/config.js');
const manifest = JSON.parse(read('frontend/manifest.webmanifest'));
const ui = read('frontend/src/ui.js');
const packageJson = JSON.parse(read('package.json'));

assert.match(index, /styles\/studio-edition\.css\?v=6\.0\.2/, 'main website loads Nexus Edition stylesheet');
assert.match(index, /src\/studio-edition\.js\?v=6\.0\.2/, 'main website loads Nexus Edition experience layer');
assert.match(iphone, /styles\/studio-edition\.css\?v=6\.0\.2/, 'iPhone entry loads same visual system');
assert.match(iphone, /src\/studio-edition\.js\?v=6\.0\.2/, 'iPhone entry loads same experience layer');
assert.match(iphone, /CHL\.start\(\)/, 'iPhone entry explicitly starts the application');
assert.match(sw, /chcn-web-nexus-v6-0-2/, 'new cache namespace forces the redesigned shell to refresh');
assert.match(sw, /studio-edition\.css\?v=6\.0\.2/, 'service worker precaches the new stylesheet');
assert.match(sw, /studio-edition\.js\?v=6\.0\.2/, 'service worker precaches the new experience layer');
assert.match(sw, /config\.js\?v=6\.0\.2/, 'service worker caches the current browser configuration URL');
assert.match(nexusCss, /nexus-command-hero/, 'Nexus visual system is present');
assert.match(js, /CHL\.mountShell\s*=\s*makeShell/, 'new shell is connected to the real router');
assert.match(js, /CHL\.routes\['\/'\]\s*=\s*function/, 'homepage uses a direct replacement without duplicate-route warnings');
assert.doesNotMatch(js, /CHL\.route\('\/'/, 'no extra duplicate homepage registration');
assert.match(js, /CHL\.apiRequest\('\/api\/live\/rooms\?limit=6'/, 'homepage requests actual backend LIVE rooms');
assert.match(js, /No live rooms are available to show right now/, 'empty LIVE list has a useful honest state');
assert.match(js, /studioMoreButton/, 'mobile navigation exposes the More menu');
assert.match(js, /studioMoreOverlay/, 'all destinations have an accessible mobile navigation sheet');
assert.match(js, /studioTabletMoreButton/, 'tablet widths retain an explicit all-pages control');
assert.match(js, /studio-skip-link/, 'keyboard users have a skip-to-content link');
assert.match(js, /chcn_studio_pending_search/, 'global search carries its real query into the search route');
assert.match(js, /CHL\.ui\.refreshCoins\(\)/, 'wallet amount comes from the existing wallet refresh service');
assert.match(css, /@media \(max-width:680px\)/, 'mobile navigation and layout breakpoint exists');
assert.match(css, /@media \(max-width:380px\)/, 'small-phone layout breakpoint exists');
assert.match(css, /prefers-reduced-motion/, 'redesign respects reduced-motion preference');
assert.match(css, /:focus-visible/, 'keyboard focus is visible');
assert.match(ui, /function\s*\(/, 'existing reusable UI module remains present');
assert.equal(config.match(/version:\s*'6\.0\.2'/)?.length, 1, 'browser-facing version is 6.0.2');
assert.equal(manifest.name, 'Creator Hub Creator Network', 'PWA manifest preserves the exact product brand');
assert.match(manifest.description, /Nexus Edition/i, 'PWA manifest describes the new visual edition');
assert.equal(packageJson.version, '6.0.2', 'source package release version is 6.0.2');
assert.ok(!fs.existsSync(path.join(root, 'android/app/release.keystore')), 'private signing keystore is not redistributed in the source package');
assert.ok(fs.existsSync(path.join(root, 'android/app/src/main/assets/web/styles/studio-edition.css')), 'Android embedded website assets were synchronized');
assert.ok(fs.existsSync(path.join(root, 'android/app/src/main/assets/web/src/studio-edition.js')), 'Android embedded runtime was synchronized');
console.log('PASS — Nexus Edition design, routing, mobile shell, honest LIVE empty states, search handoff, PWA cache and Android asset parity.');
