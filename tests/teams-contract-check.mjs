import fs from 'node:fs';
import assert from 'node:assert/strict';
const read = p => fs.readFileSync(new URL(p, import.meta.url), 'utf8');
const routes = read('../backend/src/teams-routes.js');
const ui = read('../frontend/src/pages-teams.js');
const sql = read('../database/migrations/0015_teams_backend_complete.sql');
const server = read('../backend/src/server.js');
const index = read('../frontend/index.html');
const creatorLeagueRoutes = read('../backend/src/creator-leagues.js');
for (const endpoint of ['"/api/teams"', '"join"', '"leave"', '"PATCH"', '"DELETE"', 'create_team_for_user', 'join_team_for_user', 'update_team_for_user', 'requireSupabaseUser', 'TEAM_OWNER_REQUIRED', 'OWNER_CANNOT_LEAVE', 'TEAM_FULL']) assert.ok(routes.includes(endpoint), `Missing backend contract: ${endpoint}`);
for (const feature of ['renderCreateForm', 'renderEditForm', 'renderDetail', 'Team members', 'division_code', 'recruiting', 'max_members']) assert.ok(ui.includes(feature), `Missing UI feature: ${feature}`);
for (const rule of ['create_team_for_user', 'join_team_for_user', 'update_team_for_user', 'security definer', 'pg_advisory_xact_lock', "'D5'", 'team_members']) assert.ok(sql.toLowerCase().includes(rule.toLowerCase()), `Missing SQL rule: ${rule}`);
assert.ok(server.includes('from "./teams-routes.js"'), 'Teams route module is not imported');
assert.ok(server.includes('handleTeamsRoute({'), 'Teams routes are not dispatched');
assert.ok(server.includes('PATCH, DELETE'), 'CORS must allow PATCH and DELETE');
assert.ok(index.includes('src/pages-teams.js'), 'Teams page is not loaded');
assert.ok(server.includes('from "./creator-leagues.js"'), 'Creator-league backend module is not imported');
assert.ok(server.includes('handleCreatorLeagueRoute({'), 'Creator-league API is not dispatched');
assert.ok(creatorLeagueRoutes.includes('/api/creator-leagues'), 'Creator-league API module has no canonical endpoints');
assert.ok(sql.includes('on conflict (team_id, user_id) do nothing;'), 'Migration must preserve existing membership roles');
assert.ok(sql.includes("where code = 'D5'"), 'Migration must validate the lowest division exists');
console.log('PASS — integrated Teams and creator-league backend/database contract checks.');
