import assert from 'node:assert/strict';
import { normalizePayPalEnvironment } from '../src/paypal-env.js';
assert.deepEqual(normalizePayPalEnvironment(undefined, undefined), { raw: 'sandbox', environment: 'sandbox' });
assert.deepEqual(normalizePayPalEnvironment('   ', undefined), { raw: 'sandbox', environment: 'sandbox' });
assert.deepEqual(normalizePayPalEnvironment('', ' live '), { raw: 'live', environment: 'live' });
assert.deepEqual(normalizePayPalEnvironment(' PRODUCTION ', undefined), { raw: 'production', environment: 'live' });
assert.deepEqual(normalizePayPalEnvironment('prod', undefined), { raw: 'prod', environment: 'live' });
assert.deepEqual(normalizePayPalEnvironment('test', undefined), { raw: 'test', environment: 'sandbox' });
assert.deepEqual(normalizePayPalEnvironment('sandbox', undefined), { raw: 'sandbox', environment: 'sandbox' });
assert.deepEqual(normalizePayPalEnvironment('staging', undefined), { raw: 'staging', environment: 'invalid' });
console.log('PASS — PayPal environment normalization defaults blank values safely and rejects unknown explicit values');
