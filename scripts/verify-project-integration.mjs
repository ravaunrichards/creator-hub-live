import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';

const projectRoot = path.resolve(process.argv[2] || process.cwd());
const read = (rel) => fs.readFileSync(path.join(projectRoot, rel), 'utf8');
const webHtml = read('frontend/index.html');
const androidHtml = read('android/app/src/main/assets/web/index.html');
const routes = read('frontend/src/pages-extra.js');
const webEngine = read('frontend/src/swipe-feed.js');
const androidEngine = read('android/app/src/main/assets/web/src/swipe-feed.js');
const webCss = read('frontend/styles/platform-responsive.css');
const androidCss = read('android/app/src/main/assets/web/styles/platform-responsive.css');
const webConfig = read('frontend/config.js');
const androidConfig = read('android/app/src/main/assets/web/config.js');
const webSw = read('frontend/sw.js');
const androidSw = read('android/app/src/main/assets/web/sw.js');
const pkg = JSON.parse(read('package.json'));

assert.match(webHtml, /src\/swipe-feed\.js\?v=6\.0\.3/, 'Website HTML must load engine 6.0.3.');
assert.match(androidHtml, /src\/swipe-feed\.js\?v=6\.0\.3/, 'Android HTML must load engine 6.0.3.');
assert.match(webHtml, /styles\/platform-responsive\.css\?v=6\.0\.3/, 'Website feed stylesheet version is stale.');
assert.match(androidHtml, /styles\/platform-responsive\.css\?v=6\.0\.3/, 'Android feed stylesheet version is stale.');
assert.match(routes, /CHL\.renderSwipeFeed\(o, 'foryou'\)/, 'For You route is not connected.');
assert.match(routes, /CHL\.renderSwipeFeed\(o, 'following'\)/, 'Following route is not connected.');
assert.equal(webEngine, androidEngine, 'Web and Android feed engine differ.');
assert.equal(webCss, androidCss, 'Web and Android feed styling differ.');
assert.equal(webConfig, androidConfig, 'Web and Android runtime config files differ.');
assert.match(webConfig, /version\s*:\s*['"]6\.0\.3['"]/, 'Runtime config version is stale.');
assert.equal(webSw, androidSw, 'Web and Android service workers differ.');
assert.match(webSw, /chcn-web-nexus-v6-0-3/, 'Service-worker cache key was not advanced.');
assert.match(webSw, /src\/swipe-feed\.js\?v=6\.0\.3/, 'Feed engine is missing from offline shell.');
assert.match(webSw, /styles\/platform-responsive\.css\?v=6\.0\.3/, 'Feed styles are missing from offline shell.');
assert.equal(pkg.version, '6.0.3', 'Project package version was not advanced consistently.');
console.log('PASS — Current project integration: 15 assertions.');
